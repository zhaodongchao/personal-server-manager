-- ============================================================
-- 下线「计划管理」（运维工具）与「网站管理」（应用栈）两个模块
--
-- 作者: zhaodc        创建时间: 2026-09-22
--
-- 背景：按需求移除两个功能模块，从数据库侧清理菜单、权限与数据表。
--       本迁移**只做减法**，不改动既有 V1/V6/V7 历史迁移（Flyway 校验和不可变）。
--
-- 清理对象：
--   菜单/权限：403(计划管理) + 4031~4036、502(网站管理) + 5021~5023，共 11 行
--   数据表：  ops_cron_job / ops_cron_log / app_website
--   迁移前数据量：ops_cron_job=0、ops_cron_log=6（测试执行日志）、app_website=0
--
-- 附带修正：删除后同级菜单排序补位
--   404 防火墙  4 -> 3
--   503 数据库  3 -> 2
-- ============================================================

-- ========== 1) 清理角色-菜单关联（先于菜单删除，虽无外键约束但保持语义清晰） ==========
DELETE FROM sys_role_menu
 WHERE menu_id IN (403, 4031, 4032, 4033, 4034, 4035, 4036,
                   502, 5021, 5022, 5023);

-- ========== 2) 清理菜单与权限点 ==========
DELETE FROM sys_menu
 WHERE id IN (403, 4031, 4032, 4033, 4034, 4035, 4036,
              502, 5021, 5022, 5023);

-- ========== 3) 同级菜单排序补位 ==========
UPDATE sys_menu SET sort = 3, updated_at = NOW() WHERE id = 404;  -- 防火墙（原 sort=4）
UPDATE sys_menu SET sort = 2, updated_at = NOW() WHERE id = 503;  -- 数据库（原 sort=3）

-- ========== 4) 删除数据表（先删日志表，再删主表） ==========
DROP TABLE IF EXISTS ops_cron_log;
DROP TABLE IF EXISTS ops_cron_job;
DROP TABLE IF EXISTS app_website;
