-- V23  邮箱验证码登录 + 自助注册
--
-- 前置事实：sys_user.email 自 V1 起即存在（可空），但无唯一索引。
-- 邮箱验证码登录按邮箱查用户，邮箱必须全表唯一才能唯一定位账号。
--
-- 处理：
--   1. 历史数据归一：email 为空串的置 NULL（MySQL 唯一索引允许多个 NULL，
--      但不允许多个 ''，直接建索引会对存量空串数据报错）；
--   2. 唯一索引 uk_email：注册时邮箱占用检查由应用层前置校验 +
--      数据库唯一约束兜底（防并发注册穿透）。
--
-- 注册策略（用户已确认）：
--   * 新注册用户不分配任何角色 —— 可登录但仅见个人中心，
--     业务功能由管理员在「用户管理」中分配角色后开放；
--   * 注册总开关 serverpanel.register.enabled 默认关闭（PANEL_REGISTER_ENABLED 环境变量开启）。
-- ============================================================================

-- 空串归一为 NULL（幂等：重复执行无副作用）
UPDATE sys_user SET email = NULL WHERE email = '';

-- 若存在重复非空邮箱（理论上不会发生），建索引会失败并中断迁移 ——
-- 这是刻意的：脏数据必须先人工处理，而不是被静默吞掉。
ALTER TABLE sys_user
  ADD UNIQUE KEY uk_email (email);
